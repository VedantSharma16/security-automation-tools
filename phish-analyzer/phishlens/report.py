"""Render an analysis report as Markdown or JSON."""

from __future__ import annotations

import json

from .analysis import defang

_BADGE = {"malicious": "MALICIOUS", "likely_phishing": "LIKELY PHISHING",
          "suspicious": "SUSPICIOUS", "clean": "CLEAN"}


def to_json(report: dict) -> str:
    return json.dumps(report, indent=2)


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def to_markdown(report: dict) -> str:
    s, m, iocs = report["summary"], report["message"], report["iocs"]
    out = [
        f"# Phishing Triage Report — {_BADGE[s['verdict']]}",
        "",
        f"**Risk score:** {s['risk_score']}/100 &nbsp; **Findings:** {s['finding_count']} "
        f"&nbsp; **Highest severity:** {s['highest_severity']}",
        "",
        "## Message",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Subject | {_cell(m['subject'])} |",
        f"| From | {_cell(m['from'])} |",
        f"| Reply-To | {_cell(', '.join(m['reply_to']) or '-')} |",
        f"| Return-Path | {_cell(m['return_path'] or '-')} |",
        f"| Date | {_cell(m['date'])} |",
        f"| Authentication | {_cell(', '.join(f'{k}={v}' for k, v in m['authentication'].items()) or 'none')} |",
        f"| Originating IP | {m['originating_ip'] or '-'} |",
        f"| Links / Attachments | {m['link_count']} / {m['attachment_count']} |",
        "",
    ]
    if report.get("narrative"):
        out += ["## Analyst Note", "", report["narrative"], ""]

    out += ["## Findings", ""]
    if report["findings"]:
        out += ["| Severity | Finding | Evidence | ATT&CK |", "|---|---|---|---|"]
        for f in report["findings"]:
            ev = "<br>".join(_cell(defang(e) if f["category"] == "link" else e) for e in f["evidence"][:4])
            out.append(f"| {f['severity'].upper()} | {_cell(f['title'])} | {ev} | {', '.join(f['mitre']) or '-'} |")
    else:
        out.append("No phishing indicators detected.")
    out.append("")

    if s["combos"]:
        out += ["### Correlated patterns", ""] + [f"- {c}" for c in s["combos"]] + [""]

    out += ["## Indicators of Compromise (defanged)", ""]
    if iocs["domains"]:
        out.append("**Domains:** " + ", ".join(f"`{defang(d)}`" for d in iocs["domains"]))
    if iocs["urls"]:
        out += ["", "**URLs:**"] + [f"- `{defang(u)}`" for u in iocs["urls"]]
    if iocs["ips"]:
        out += ["", "**IPs:** " + ", ".join(f"`{defang(i)}`" for i in iocs["ips"])]
    if iocs["attachments"]:
        out += ["", "**Attachments:**"] + [f"- `{a['filename']}` sha256 `{a['sha256']}`" for a in iocs["attachments"]]
    out += ["", "## Recommended Actions", ""] + [f"- {a}" for a in report["recommended_actions"]]
    out += ["", f"<sub>Generated by {report['tool']} at {report['analyzed_at']}</sub>", ""]
    return "\n".join(out)


def iocs_csv(report: dict) -> str:
    """Flat ``type,value,source`` rows, ready for a blocklist or SIEM lookup import."""
    iocs, src = report["iocs"], report.get("source", "")
    rows = ["type,value,source"]
    rows += [f"domain,{d},{src}" for d in iocs["domains"]]
    rows += [f"url,\"{u}\",{src}" for u in iocs["urls"]]
    rows += [f"ip,{i},{src}" for i in iocs["ips"]]
    rows += [f"sha256,{a['sha256']},{src}" for a in iocs["attachments"]]
    return "\n".join(rows) + "\n"
